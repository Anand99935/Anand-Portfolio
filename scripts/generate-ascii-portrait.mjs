/* Converts a portrait photo into the ASCII grid rendered by
   components/AsciiPortrait.tsx. The photo itself never ships — only the
   generated character grid lands in lib/asciiPortrait.ts.

   Usage: node scripts/generate-ascii-portrait.mjs <photo.jpg> [cols]
*/
import { writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const [, , input, colsArg] = process.argv;
if (!input) {
  console.error("Usage: node scripts/generate-ascii-portrait.mjs <photo> [cols]");
  process.exit(1);
}

const COLS = Number(colsArg ?? 120);
/* Monospace cells are ~2x taller than wide; squash rows to compensate. */
const CELL_ASPECT = 0.5;
/* Sparse → dense. Dense glyphs read as "lit" on the site's dark surface. */
const RAMP = " .'`^,:;Il!i><~+_-?][}{1)(|/tfjrxnuvczXYUJCLQ0OZmwqpdbkhao*#MW&8%B@$";

const meta = await sharp(input).metadata();
/* Head-and-shoulders crop tuned for the supplied portrait. */
const crop = {
  left: Math.round(meta.width * 0.08),
  top: Math.round(meta.height * 0.14),
  width: Math.round(meta.width * 0.84),
  height: Math.round(meta.height * 0.72),
};
const rows = Math.round((COLS * (crop.height / crop.width)) * CELL_ASPECT);

const { data } = await sharp(input)
  .extract(crop)
  .resize(COLS, rows, { fit: "fill" })
  .removeAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

/* Separate luminance pass with local contrast (CLAHE) so eyes, glasses
   and beard survive the downsample instead of flattening into skin. */
const { data: luma } = await sharp(input)
  .extract(crop)
  .greyscale()
  .clahe({ width: 48, height: 48, maxSlope: 4 })
  .resize(COLS, rows, { fit: "fill", kernel: "lanczos3" })
  .sharpen({ sigma: 1.4 })
  .raw()
  .toBuffer({ resolveWithObject: true });

/* Background mask: the wall is a bright neutral grey/cream (red ≈ green),
   while skin is warm (red well above green) and hair/shirt are dark. */
const isBackdrop = (r, g, b) => {
  const l = (r * 0.299 + g * 0.587 + b * 0.114) / 255;
  return l > 0.55 && r - g < 14;
};

const cells = [];
for (let i = 0; i < COLS * rows; i++) {
  const [r, g, b] = [data[i * 3], data[i * 3 + 1], data[i * 3 + 2]];
  if (isBackdrop(r, g, b)) {
    cells.push(-1);
    continue;
  }
  cells.push(luma[i] / 255);
}

/* Rank-equalise the foreground so the full glyph ramp is used — without
   it the face bunches into a few dense glyphs and loses its features. */
const sorted = cells.filter((l) => l >= 0).sort((a, b) => a - b);
const rankOf = (l) => {
  let lo = 0;
  let hi = sorted.length;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (sorted[mid] < l) lo = mid + 1;
    else hi = mid;
  }
  return lo / (sorted.length - 1 || 1);
};

/* Foreground brightness → glyph density, with a floor so dark hair and
   the navy shirt still read as solid texture rather than empty space. */
const FLOOR = Number(process.env.ASCII_FLOOR ?? 0.18);
const GAMMA = Number(process.env.ASCII_GAMMA ?? 1.4);
const lines = [];
for (let y = 0; y < rows; y++) {
  let line = "";
  for (let x = 0; x < COLS; x++) {
    const l = cells[y * COLS + x];
    if (l < 0) {
      line += " ";
      continue;
    }
    const t = FLOOR + (1 - FLOOR) * Math.pow(rankOf(l), GAMMA);
    line += RAMP[Math.min(RAMP.length - 1, Math.floor(t * RAMP.length))];
  }
  lines.push(line);
}

const out = path.resolve("lib/asciiPortrait.ts");
await writeFile(
  out,
  `/* Generated by scripts/generate-ascii-portrait.mjs — do not edit by hand. */\n` +
    `export const ASCII_PORTRAIT: readonly string[] = ${JSON.stringify(lines, null, 2)};\n`,
);
console.log(lines.join("\n"));
console.log(`\n${COLS}x${rows} → ${out}`);
